-- Customer birthdays (captured in the billing panel) + birthday offers.
-- Safe to run more than once.

CREATE TABLE IF NOT EXISTS public.customer_profiles (
  phone       TEXT PRIMARY KEY,               -- last 10 digits
  name        TEXT,
  birth_date  DATE,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.birthday_offers (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  label       TEXT NOT NULL,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE public.store_settings ADD COLUMN IF NOT EXISTS birthday_message TEXT;

GRANT ALL ON public.customer_profiles, public.birthday_offers TO anon, authenticated;
GRANT ALL ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated;

DO $$
DECLARE t TEXT;
BEGIN
  FOREACH t IN ARRAY ARRAY['customer_profiles', 'birthday_offers'] LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('DROP POLICY IF EXISTS "Allow all" ON public.%I', t);
    EXECUTE format('CREATE POLICY "Allow all" ON public.%I FOR ALL TO anon, authenticated USING (true) WITH CHECK (true)', t);
  END LOOP;
END $$;

INSERT INTO public.birthday_offers (label)
SELECT '10% off on your next purchase'
WHERE NOT EXISTS (SELECT 1 FROM public.birthday_offers);
